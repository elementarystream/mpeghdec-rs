"""Generate Rust `extern "C"` declarations for the C shims in crates/cref/shim/.

Every function definition in a shim file whose name starts with `cref_` and that fits on one
line (`RET cref_name(ARGS) {`) is turned into a declaration in crates/cref/src/<shim>.rs.

Usage: scripts/codegen/gen_cref_bindings.py [shim-name ...]   (default: all shims)
"""
import os, re, sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SHIM = os.path.join(REPO, 'crates', 'cref', 'shim')
OUT = os.path.join(REPO, 'crates', 'cref', 'src')

SCALARS = {
    'void': '()', 'INT': 'i32', 'int': 'i32', 'LONG': 'i32', 'FIXP_DBL': 'i32', 'UINT': 'u32',
    'unsigned': 'u32', 'ULONG': 'u32', 'SHORT': 'i16', 'FIXP_SGL': 'i16', 'USHORT': 'u16',
    'SCHAR': 'i8', 'UCHAR': 'u8', 'char': 'i8', 'INT64': 'i64', 'UINT64': 'u64',
    'int32_t': 'i32', 'uint32_t': 'u32', 'int16_t': 'i16', 'uint16_t': 'u16', 'uint8_t': 'u8',
    'int8_t': 'i8', 'int64_t': 'i64', 'uint64_t': 'u64', 'float': 'f32', 'double': 'f64',
    'size_t': 'usize',
}

RUST_KEYWORDS = {'in', 'fn', 'type', 'ref', 'mod', 'use', 'loop', 'match', 'move', 'box', 'self',
                 'impl', 'trait', 'where', 'as', 'crate', 'dyn', 'pub', 'mut', 'let', 'gen'}

def rtype(t):
    t = t.strip()
    const = t.startswith('const ')
    if const: t = t[6:].strip()
    stars = t.count('*'); base = t.replace('*', '').strip()
    r = SCALARS.get(base, 'core::ffi::c_void')
    for _ in range(stars):
        r = ('*const ' if const else '*mut ') + r
        const = False
    return r

def gen(name):
    src = open(os.path.join(SHIM, name + '.cpp')).read()
    decls = []
    for m in re.finditer(r'^([A-Za-z_][\w\s\*]*?)\s*\b(cref_\w+)\(([^)]*)\)\s*\{', src, re.M):
        ret, fn, args = m.group(1), m.group(2), m.group(3).strip()
        params = []
        if args and args != 'void':
            for i, a in enumerate(args.split(',')):
                a = a.strip()
                am = re.match(r'(.*?)(\w+)$', a)
                ty, nm = am.group(1), am.group(2)
                if nm in RUST_KEYWORDS: nm += '_'
                params.append(f'{nm}: {rtype(ty)}')
        rt = rtype(ret)
        sig = f'    pub fn {fn}({", ".join(params)})' + ('' if rt == '()' else f' -> {rt}') + ';'
        decls.append(sig)
    out = ['// Rust port of the Fraunhofer FDK MPEG-H Software (mpeghdec r4.0.1).',
           '// Third-Party Modified Version of the Fraunhofer FDK MPEG-H Software.',
           '// See LICENSE.txt for the complete license text.', '',
           '// Generated by scripts/codegen/gen_cref_bindings.py from shim/%s.cpp. Do not edit.' % name, '',
           '#![allow(clippy::missing_safety_doc)]', '', 'extern "C" {'] + decls + ['}', '']
    open(os.path.join(OUT, name + '.rs'), 'w').write('\n'.join(out))
    print(f'{name}: {len(decls)} functions')

names = sys.argv[1:] or sorted(f[:-4] for f in os.listdir(SHIM) if f.endswith('.cpp'))
for n in names: gen(n)
