"""Generate crates/gvbap/src/tables/*.rs from libgVBAPRenderer/src/tables.cpp.

tables.cpp defines 72 imaginary speaker tables and 224 speaker superset tables that are selected
by a CICP index (getImagSpeakerTable(), getSpeakerSuperSetTable()). Like scripts/codegen/dump_table.py,
this tool compiles a small program against the C++ source and prints the exact table contents,
here by calling the two getter functions for every possible index, so that the table structure
(including shared arrays) is reproduced without retyping anything.

Usage: scripts/codegen/gen_gvbap_tables.py && cargo fmt --all
       (writes crates/gvbap/src/tables/{imag,superset}.rs)

Environment:
  MPEGHDEC_C_DIR   C++ source checkout (default: work/reference/src)
"""
import os, subprocess, sys, tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import dump_table  # noqa: E402

REPO = dump_table.REPO
CDIR = dump_table.CDIR
OUT = os.path.join(REPO, 'crates', 'gvbap', 'src', 'tables')
MAX_INDEX = 1024

HEADER = '''// Rust port of the Fraunhofer FDK MPEG-H Software (mpeghdec r4.0.1).
// Third-Party Modified Version of the Fraunhofer FDK MPEG-H Software.
// See LICENSE.txt for the complete license text.
//
// Ported from libgVBAPRenderer/src/tables.cpp.
// Generated by scripts/codegen/gen_gvbap_tables.py. Do not edit.

'''

PROG = r'''#include "%s"
#include <stdio.h>
static void arr(const char* tag, const void* p, int n, int dbl) {
  printf("A %%s %%p %%d", tag, p, n);
  for (int i = 0; i < n; i++) printf(" %%d", dbl ? (int)((const FIXP_DBL*)p)[i] : ((const int*)p)[i]);
  printf("\n");
}
int main() {
  for (int i = -1; i < %d; i++) {
    const imagSpeakerTable* t = getImagSpeakerTable(i);
    if (t) {
      printf("I %%d %%p %%d %%p %%p %%p %%d %%d %%p\n", i, (const void*)t, t->numGhost, (const void*)t->aziGhost,
             (const void*)t->eleGhost, (const void*)t->initialPoly, t->numRow, t->numCol,
             (const void*)t->downMixData);
      arr("azi", t->aziGhost, t->numGhost, 0);
      arr("ele", t->eleGhost, t->numGhost, 0);
      arr("poly", t->initialPoly, 5, 0);
      arr("dmx", t->downMixData, t->numRow * t->numCol, 1);
    }
  }
  for (int i = -1; i < %d; i++) {
    const speakerSuperSetTable* t = getSpeakerSuperSetTable(i);
    if (t) {
      printf("S %%d %%p %%d %%d %%d %%p\n", i, (const void*)t, t->supersetCicpIndex, t->nSpeakersSuperSet,
             t->nSpeakersSubSet, (const void*)t->downMixData);
      arr("sdmx", t->downMixData, t->nSpeakersSuperSet * t->nSpeakersSubSet, 1);
    }
  }
  return 0;
}
'''


def run():
    src = os.path.join(CDIR, 'src', 'libgVBAPRenderer', 'src', 'tables.cpp')
    with tempfile.TemporaryDirectory() as td:
        cpp = os.path.join(td, 'gen.cpp'); exe = os.path.join(td, 'gen')
        open(cpp, 'w').write(PROG % (src, MAX_INDEX, MAX_INDEX))
        cmd = ['c++', '-std=c++11', '-O0', '-w', '-DMPEGHDEC_INTERNAL=1', '-DMPEGHDEC_STATIC=1']
        cmd += ['-I' + d for d in dump_table.include_dirs()] + [cpp, '-o', exe]
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode != 0:
            sys.stderr.write(r.stderr); sys.exit(1)
        return subprocess.run([exe], capture_output=True, text=True, check=True).stdout


def hexv(v):
    return f'0x{v & 0xFFFFFFFF:08X}' if v >= 0 else f'0x{v & 0xFFFFFFFF:08X}u32 as i32'


def emit_array(out, name, ty, vals, per_line, fmt):
    out.append(f'static {name}: [{ty}; {len(vals)}] = [')
    items = [fmt(v) for v in vals]
    for i in range(0, len(items), per_line):
        out.append('    ' + ', '.join(items[i:i + per_line]) + ',')
    out.append('];')


def main():
    lines = run().splitlines()
    arrays = {}  # pointer -> (values, name)
    imag = []    # (index, fields)
    sup = []
    for ln in lines:
        f = ln.split()
        if f[0] == 'I':
            imag.append((int(f[1]), f[3:]))
        elif f[0] == 'S':
            sup.append((int(f[1]), f[3:]))
        elif f[0] == 'A':
            tag, ptr, n = f[1], f[2], int(f[3])
            vals = [int(v) for v in f[4:4 + n]]
            idx = (imag[-1][0] if tag in ('azi', 'ele', 'poly', 'dmx') else sup[-1][0])
            if ptr in arrays:
                old, name = arrays[ptr]
                if len(vals) > len(old):
                    assert vals[:len(old)] == old
                    arrays[ptr] = (vals, name)
                else:
                    assert old[:len(vals)] == vals
            else:
                base = {'azi': 'AZI_GHOST', 'ele': 'ELE_GHOST', 'poly': 'INITIAL_POLY',
                        'dmx': 'DOWN_MIX_DATA', 'sdmx': 'SUPER_SET_DOWN_MIX_DATA'}[tag]
                arrays[ptr] = (vals, f'{base}_CICP_{idx:03d}' if tag == 'sdmx' else f'{base}_CICP_{idx}')

    os.makedirs(OUT, exist_ok=True)

    # imaginary speaker tables
    out = [HEADER.rstrip('\n'), '',
           '//! Imaginary (ghost) loudspeakers, initial polyhedra and downmix matrices for loudspeaker',
           '//! setups with known triangulation (`getImagSpeakerTable()`).', '',
           'use crate::quick_hull::ImagSpeakerTable;', '']
    used = set()
    for idx, fl in imag:
        for ptr in (fl[1], fl[2], fl[3], fl[6]):
            if ptr in used:
                continue
            used.add(ptr)
            vals, name = arrays[ptr]
            if name.startswith('DOWN_MIX'):
                emit_array(out, name, 'i32', vals, 6, hexv)
            else:
                emit_array(out, name, 'i32', vals, 16, str)
            out.append('')
    for idx, fl in imag:
        num_ghost, azi, ele, poly, num_row, num_col, dmx = fl
        out.append(f'static IMAG_SPEAKER_TABLE_CICP_{idx}: ImagSpeakerTable = ImagSpeakerTable {{')
        out.append(f'    num_ghost: {num_ghost},')
        out.append(f'    azi_ghost: &{arrays[azi][1]},')
        out.append(f'    ele_ghost: &{arrays[ele][1]},')
        out.append(f'    initial_poly: &{arrays[poly][1]},')
        out.append(f'    num_row: {num_row},')
        out.append(f'    num_col: {num_col},')
        out.append(f'    down_mix_data: &{arrays[dmx][1]},')
        out.append('};')
        out.append('')
    out.append('/// `getImagSpeakerTable(cicpIdx)`')
    out.append('pub fn get_imag_speaker_table(cicp_idx: i32) -> Option<&\'static ImagSpeakerTable> {')
    out.append('    match cicp_idx {')
    for idx, _ in imag:
        out.append(f'        {idx} => Some(&IMAG_SPEAKER_TABLE_CICP_{idx}),')
    out.append('        _ => None,')
    out.append('    }')
    out.append('}')
    open(os.path.join(OUT, 'imag.rs'), 'w').write('\n'.join(out) + '\n')

    # superset tables
    out = [HEADER.rstrip('\n'), '',
           '//! Loudspeaker supersets and superset-to-subset downmix matrices',
           '//! (`getSpeakerSuperSetTable()`).', '',
           'use crate::quick_hull::SpeakerSuperSetTable;', '']
    used = set()
    for idx, fl in sup:
        ptr = fl[3]
        if ptr in used:
            continue
        used.add(ptr)
        vals, name = arrays[ptr]
        emit_array(out, name, 'i32', vals, 6, hexv)
        out.append('')
    for idx, fl in sup:
        sidx, nsup, nsub, dmx = fl
        out.append(f'static SPEAKER_SUPER_SET_TABLE_CICP_{idx:03d}: SpeakerSuperSetTable = SpeakerSuperSetTable {{')
        out.append(f'    superset_cicp_index: {sidx},')
        out.append(f'    n_speakers_super_set: {nsup},')
        out.append(f'    n_speakers_sub_set: {nsub},')
        out.append(f'    down_mix_data: &{arrays[dmx][1]},')
        out.append('};')
        out.append('')
    out.append('/// `getSpeakerSuperSetTable(cicpIdx)`')
    out.append('pub fn get_speaker_super_set_table(cicp_idx: i32) -> Option<&\'static SpeakerSuperSetTable> {')
    out.append('    match cicp_idx {')
    for idx, _ in sup:
        out.append(f'        {idx} => Some(&SPEAKER_SUPER_SET_TABLE_CICP_{idx:03d}),')
    out.append('        _ => None,')
    out.append('    }')
    out.append('}')
    open(os.path.join(OUT, 'superset.rs'), 'w').write('\n'.join(out) + '\n')
    print(f'{len(imag)} imaginary speaker tables, {len(sup)} superset tables')


if __name__ == '__main__':
    main()
