/// `FIXP_STB`: single sine table value.
pub type FixpStb = FixpSgl;
/// `FIXP_STP`: packed sine table value (cos, sin).
pub type FixpStp = FixpSpk;
/// `FIXP_WTB`: single window table value.
pub type FixpWtb = FixpSgl;
/// `FIXP_WTP`: packed window table value.
pub type FixpWtp = FixpSpk;

/// `STC(a)`: sine table coefficient from a `FIXP_DBL` constant.
#[inline(always)]
pub const fn stc(a: i32) -> FixpStb {
    fx_dbl2fxconst_sgl(a)
}

/// `WTC(a)`: window table coefficient from a `FIXP_DBL` constant.
#[inline(always)]
pub const fn wtc(a: i32) -> FixpWtb {
    fx_dbl2fxconst_sgl(a)
}

/// `STCP(cos, sin)`
#[inline(always)]
pub const fn stcp(cos: i32, sin: i32) -> FixpStp {
    FixpSpk::new(stc(cos), stc(sin))
}

/// `WTCP(a, b)`
#[inline(always)]
pub const fn wtcp(a: i32, b: i32) -> FixpWtp {
    FixpSpk::new(wtc(a), wtc(b))
}

const fn spk(re: i16, im: i16) -> FixpSpk {
    FixpSpk::new(re, im)
}

