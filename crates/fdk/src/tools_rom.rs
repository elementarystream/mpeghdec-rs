/// `getBitstreamElementList(aot, epConfig, nChannels, layer, elFlags)`: get the elementary
/// stream pieces list for the given parameters (`None` for unsupported AOTs).
pub fn get_bitstream_element_list(
    aot: AudioObjectType,
    _ep_config: i8,
    n_channels: u8,
    _layer: u8,
    el_flags: u32,
) -> Option<&'static ElementList> {
    match aot {
        AOT_MPEGH3DA | AOT_USAC => {
            if el_flags & AC_EL_USAC_LFE != 0 {
                debug_assert!(n_channels == 1);
                return Some(&NODE_USAC_LFE_EPC0);
            }
            if n_channels == 1 {
                Some(&NODE_USAC_SCE_EPC0)
            } else {
                Some(&NODE_USAC_CPE_EPC0)
            }
        }
        _ => None,
    }
}

