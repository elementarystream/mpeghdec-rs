/// `windowSlopes[2][4][10]`: helper table containing the length, raster and shape mapping to
/// individual window slope tables.
///
/// `[shape: 0 sine, 1 KBD][raster: 0 radix 2, 1 10 ms, 2 3/4 of radix 2][ceil(log2(length))]`.
/// The sine table starts at length 4, the KBD table at length 64. Prefer
