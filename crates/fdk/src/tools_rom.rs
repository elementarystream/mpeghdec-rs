/// `FDKgetWindowSlope(length, shape)`: window slope of the given length and shape.
///
/// `shape` 0 selects the sine window, 1 the Kaiser-Bessel-derived window; other values are masked
/// with 1. The C++ function returns `NULL` (and asserts) if the window slope is not available;
/// this port returns `None` in that case.
pub fn fdk_get_window_slope_opt(length: i32, shape: i32) -> WindowSlope {
    // Get ld2 of length - 2 + 1
    //   -2: because first table entry is window of size 4
    //   +1: because we already include +1 because of ceil(log2(length))
    let mut ld2_length = DFRACT_BITS - 1 - f_normz(length) - 1;

    // Extract sort of "eigenvalue" (the 4 left most bits) of length.
    let raster = match length >> (ld2_length - 2) {
        0x8 => {
            // radix 2: revert + 1 because of ceil(log2(length)) from above.
            ld2_length -= 1;
            0
        }
        0xf => 1, // 10 ms
        0xc => 2, // 3/4 of radix 2
        _ => 0,
    };

    // The table for sine windows (shape == 0) is 4 entries longer.
    if shape == 1 {
        ld2_length -= 4;
    }

    WINDOW_SLOPES[(shape & 1) as usize][raster].get(ld2_length as usize).copied().flatten()
}

/// `FDKgetWindowSlope(length, shape)`: window slope of the given length and shape.
///
/// Panics if the window slope is not available (the C++ code asserts and returns `NULL`). See
/// [`fdk_get_window_slope_opt`].
pub fn fdk_get_window_slope(length: i32, shape: i32) -> &'static [FixpWtp] {
    match fdk_get_window_slope_opt(length, shape) {
        Some(w) => w,
        None => panic!("FDKgetWindowSlope: no window slope for length {length}, shape {shape}"),
    }
}

